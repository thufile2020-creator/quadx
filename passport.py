"""Turn independently calculated activity records into an auditable supplier passport.

Note: Emissions are estimates, NOT third-party verification or certification.
Report values are calculated in this module from explicit activity data and
supplied emission factors, not generated by a language model.
"""

from datetime import date
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP
import re


class PassportError(ValueError):
    """Invalid or incomplete input records."""


def _text(value, field, max_length=300, required=True):
    if not isinstance(value, str):
        raise PassportError(f"{field} must be text")
    value = value.strip()
    if required and not value:
        raise PassportError(f"{field} is required")
    if len(value) > max_length:
        raise PassportError(f"{field} exceeds {max_length} characters")
    return value


def _positive_decimal(value, field, allow_zero=True):
    if isinstance(value, bool) or value is None:
        raise PassportError(f"{field} must be a number")
    try:
        decimal = Decimal(str(value))
    except (InvalidOperation, ValueError):
        raise PassportError(f"{field} must be a number") from None
    if not decimal.is_finite() or decimal < 0 or (not allow_zero and decimal == 0):
        raise PassportError(f"{field} must be {'positive' if not allow_zero else 'non-negative'}")
    return decimal


def _display_num(value, digits=3):
    quantizer = Decimal('1').scaleb(-digits)
    return float(value.quantize(quantizer, rounding=ROUND_HALF_UP))


def build_passport(payload):
    """Validate input and create JSON-serializable passport dict.

    Data contract documented in README.md and sample_data/factory.json.
    All factors are provided by backend / carbon logic team and remain
    traceable to their source. No hardcoded production factor is used.
    """
    if not isinstance(payload, dict):
        raise PassportError("The payload must be a JSON object")
    business = payload.get("business")
    period = payload.get("period")
    activities = payload.get("activities")
    if not isinstance(business, dict) or not isinstance(period, dict):
        raise PassportError("business and period must be objects")
    if not isinstance(activities, list) or not activities or len(activities) > 500:
        raise PassportError("activities must contain 1 to 500 records")

    report_id = _text(payload.get("report_id", ""), "report_id", 64)
    if not re.fullmatch(r"[A-Za-z0-9_-]{3,64}", report_id):
        raise PassportError("report_id may only contain letters, digits, _ and -")

    dates = {}
    for key in ("start", "end"):
        text = _text(period.get(key, ""), f"period.{key}", 10)
        try:
            dates[key] = date.fromisoformat(text)
        except ValueError:
            raise PassportError(f"period.{key} must be YYYY-MM-DD") from None
    if dates["end"] < dates["start"]:
        raise PassportError("period.end must be on or after period.start")

    business_out = {
        "name": _text(business.get("name", ""), "business.name", 120),
        "industry": _text(business.get("industry", ""), "business.industry", 120),
        "location": _text(business.get("location", ""), "business.location", 120),
        "supplier_id": _text(business.get("supplier_id", ""), "business.supplier_id", 80),
    }

    rows, scopes, ids = [], {"Scope 1": Decimal('0'), "Scope 2": Decimal('0'), "Scope 3": Decimal('0')}, set()
    exact_total = Decimal('0')
    demo_factor = False
    for index, item in enumerate(activities, 1):
        if not isinstance(item, dict):
            raise PassportError(f"activities[{index}] must be an object")
        activity_id = _text(item.get("id", ""), f"activities[{index}].id", 80)
        if activity_id in ids:
            raise PassportError(f"Duplicate activity id: {activity_id}")
        ids.add(activity_id)
        scope = _text(item.get("scope", ""), f"activities[{index}].scope", 20)
        if scope not in scopes:
            raise PassportError("scope must be Scope 1, Scope 2 or Scope 3")
        quantity = _positive_decimal(item.get("quantity"), "quantity")
        factor = _positive_decimal(item.get("emission_factor"), "emission_factor")
        source = _text(item.get("source", ""), "source", 120)
        unit = _text(item.get("unit", ""), "unit", 30)
        factor_unit = _text(item.get("factor_unit", ""), "factor_unit", 80)
        factor_source = _text(item.get("factor_source", ""), "factor_source", 220)
        factor_year = item.get("factor_year")
        if isinstance(factor_year, bool) or not isinstance(factor_year, int) or not 1990 <= factor_year <= 2100:
            raise PassportError("factor_year must be a valid integer year")
        evidence = _text(item.get("evidence_file", ""), "evidence_file", 160, required=False)
        record_emissions = quantity * factor
        exact_total += record_emissions
        scopes[scope] += record_emissions
        demo_factor = demo_factor or "DEMO" in factor_source.upper() or "ILLUSTRATIVE" in factor_source.upper()
        rows.append({
            "id": activity_id,
            "source": source,
            "scope": scope,
            "quantity": _display_num(quantity),
            "unit": unit,
            "emission_factor": _display_num(factor, 6),
            "factor_unit": factor_unit,
            "factor_source": factor_source,
            "factor_year": factor_year,
            "evidence_file": evidence,
            "kg_co2e": _display_num(record_emissions),
        })

    production = payload.get("production")
    production_out = None
    intensity = None
    if production is not None:
        if not isinstance(production, dict):
            raise PassportError("production must be an object")
        production_quantity = _positive_decimal(production.get("quantity"), "production.quantity", allow_zero=False)
        production_out = {
            "quantity": _display_num(production_quantity),
            "unit": _text(production.get("unit", ""), "production.unit", 40),
            "allocation_note": _text(production.get("allocation_note", ""), "production.allocation_note", 300),
        }
        intensity = _display_num(exact_total / production_quantity, 6)

    notes = payload.get("quality_notes", [])
    if not isinstance(notes, list) or len(notes) > 20:
        raise PassportError("quality_notes must be a list with at most 20 notes")
    notes = [_text(note, "quality_notes[]", 280) for note in notes]

    return {
        "schema_version": "1.0",
        "report_id": report_id,
        "status": "DEMO / NOT VERIFIED" if demo_factor else "SELF-REPORTED / NOT VERIFIED",
        "business": business_out,
        "period": {"start": dates['start'].isoformat(), "end": dates['end'].isoformat()},
        "total_kg_co2e": _display_num(exact_total),
        "scope_totals_kg_co2e": {key: _display_num(value) for key, value in scopes.items()},
        "activities": rows,
        "production": production_out,
        "operational_intensity_kg_co2e_per_unit": intensity,
        "methodology": "Sum of activity quantities multiplied by explicitly documented emission factors. Scope classification supplied by the reporting team.",
        "quality_notes": notes,
        "limitations": [
            "Self-reported estimates, not independently verified or certified.",
            "Coverage is limited to the activity records listed in this passport; omitted sources are not zero-emission.",
            "Operational per-unit intensity is not a full lifecycle product carbon footprint.",
        ] + (["DEMO emission factors are illustrative and must be replaced with location-, activity- and reporting-year-appropriate documented values before external reporting."] if demo_factor else []),
    }
